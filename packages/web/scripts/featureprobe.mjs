import { chromium } from "playwright";
const [url, out] = process.argv.slice(2);
const b = await chromium.launch({ channel: "chrome", headless: true, args: ["--use-gl=angle", "--use-angle=swiftshader", "--enable-unsafe-swiftshader", "--autoplay-policy=no-user-gesture-required"] });
const ctx = await b.newContext({ viewport: { width: 1300, height: 760 }, acceptDownloads: true });
const p = await ctx.newPage(); const errs = []; p.on("pageerror", (e) => errs.push(String(e).slice(0, 160)));
await p.goto(url, { waitUntil: "load" }); await p.waitForFunction(() => globalThis.__agentTheatre?.player, null, { timeout: 20000 }); await p.waitForTimeout(1500);
await p.click(".stage", { position: { x: 100, y: 100 } });
await p.getByRole("button", { name: "Whole repo" }).click(); await p.waitForTimeout(2500);
await p.screenshot({ path: out + "/overview.png" });
const z0 = await p.evaluate(() => globalThis.__agentTheatre.player.camera.scale);
await p.mouse.move(650, 380); await p.mouse.wheel(0, -600); await p.waitForTimeout(1500);
const z1 = await p.evaluate(() => globalThis.__agentTheatre.player.camera.scale);
const dl = p.waitForEvent("download", { timeout: 15000 });
await p.getByRole("button", { name: "Export clip" }).click(); await p.waitForTimeout(3500);
await p.getByRole("button", { name: /Stop & save/ }).click();
const d = await dl; const path = await d.path();
const { statSync } = await import("node:fs");
console.log(JSON.stringify({ overviewZoom: +z0.toFixed(3), afterWheel: +z1.toFixed(3), download: d.suggestedFilename(), bytes: path ? statSync(path).size : 0, errs }));
await b.close();
